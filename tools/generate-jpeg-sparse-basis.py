"""Generate original fixed-point T.81 basis data from the owned frozen policy."""
from fractions import Fraction
import hashlib
from pathlib import Path
import re
import struct
import sys

root = Path(__file__).resolve().parents[1]
source = (root / 'src/Lokad.Image/Internal/JpegTransform.cs').read_text(encoding='utf-8')
body = source.split('private static readonly double[] Cosines =')[1].split('];')[0]
cosines = [float(v) for v in re.findall(r'-?\d+\.\d+(?:[eE][-+]?\d+)?', body)]
assert len(cosines) == 64
weights = [round(Fraction(cosines[x * 8 + u]) * Fraction(cosines[y * 8 + v]) * 16384)
           for v in range(8) for u in range(8) for y in range(8) for x in range(8)]
assert min(weights) >= -32768 and max(weights) <= 32767
digest = hashlib.sha256(struct.pack('<4096h', *weights)).hexdigest()
lines = ['using System;', '', 'namespace Lokad.Image.Internal;', '',
         '// Original T.81 A.3.3 geometry, quantized from the owned frozen binary64',
         '// basis using exact rational nearest-even rounding; frequency, y, x order.',
         '// Generated by tools/generate-jpeg-sparse-basis.py. No upstream table.',
         '// SHA256 of little-endian shorts: ' + digest,
         'internal static class JpegSparseBasis', '{',
         '    internal static ReadOnlySpan<short> Weights =>', '    [']
lines += ['        ' + ', '.join(str(v) for v in weights[i:i + 16]) + ','
          for i in range(0, len(weights), 16)]
lines += ['    ];', '}', '']
text = '\n'.join(lines)
output = root / 'src/Lokad.Image/Internal/JpegSparseBasis.generated.cs'
if '--check' in sys.argv:
    assert output.read_text(encoding='utf-8') == text, 'Generated JPEG sparse basis differs.'
else:
    output.write_text(text, encoding='utf-8', newline='\n')
print('Owned Q16 JPEG basis verified: ' + digest)
