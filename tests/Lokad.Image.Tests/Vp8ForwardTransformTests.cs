    public static IEnumerable<object[]> Fragments()
    {
        for (var i = 0; i < NativeFragments.Length; i++) yield return [i, NativeFragments[i]];
    }

    [Theory]
    [MemberData(nameof(Fragments))]
    public void SignedFragmentsMatchEveryNativeCoefficientAndPermitOverlappingBuffers(int fragment, short[] expected)
    {
        var residual = new short[18]; residual[16] = 789; residual[17] = -789;
        for (var p = 0; p < 16; p++)
            residual[p] = (short)(fragment switch
            {
                1 => 255, 2 => -255, 3 => (p / 4 + p % 4) % 2 == 0 ? 255 : -255,
                >= 4 when p == (fragment - 4) / 2 => (fragment - 4) % 2 == 0 ? 255 : -255,
                _ => 0
            });
        var original = residual.ToArray(); var output = Enumerable.Repeat((short)0x5a5a, 18).ToArray();
        Vp8ForwardTransform.Dct(residual, output);
        Assert.Equal(expected, output[..16]); Assert.Equal(original, residual);
        Assert.Equal((short)0x5a5a, output[16]); Assert.Equal((short)0x5a5a, output[17]);
        Vp8ForwardTransform.Dct(residual, residual);
        Assert.Equal(expected, residual[..16]); Assert.Equal(original[16..], residual[16..]);
    }

    private static int AppendPlane(ReadOnlySpan<byte> plane, int stride, IncrementalHash hash)
    {
        Span<short> residual = stackalloc short[16]; Span<short> coefficients = stackalloc short[16];
        Span<byte> bytes = stackalloc byte[32]; var blocks = 0;
        for (var y = 0; y < plane.Length / stride; y += 4)
        for (var x = 0; x < stride; x += 4)
        {
            for (var dy = 0; dy < 4; dy++)
            for (var dx = 0; dx < 4; dx++) residual[dy * 4 + dx] = (short)(plane[(y + dy) * stride + x + dx] - 128);
            Vp8ForwardTransform.Dct(residual, coefficients);
            for (var i = 0; i < 16; i++) BinaryPrimitives.WriteInt16LittleEndian(bytes.Slice(i * 2, 2), coefficients[i]);
            hash.AppendData(bytes); blocks++;
        }
        return blocks;
    }

    [Fact]
    public void AllOpaqueControlLumaAndChromaBlocksMatchPinnedNativeCoefficients()
    {
        using var root = new TestMemoryBudget(16_000_000);
        using var source = OriginalVp8lControls.Buffer("opaque", 8, root);
        using var context = new OperationContext(new() { MemoryBudget = root }, default);
        using var input = Vp8PreparedInput.Create(source, context); input.CleanupTransparentArea();
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        var retained = root.Bytes; var original = Vp8PreparedInputTests.Hash(input);
        var blocks = AppendPlane(input.Y, input.Stride, hash) + AppendPlane(input.U, input.Stride / 2, hash) + AppendPlane(input.V, input.Stride / 2, hash);
        Assert.Equal(13464, blocks);
        Assert.Equal("c6d3f52d3dc7ac14a798919f533d1e96c94cd5f1aa5f18780dbe9ea339ec2abc", Convert.ToHexStringLower(hash.GetHashAndReset()));
        Assert.Equal(original, Vp8PreparedInputTests.Hash(input)); Assert.Equal(retained, root.Bytes);
    }

