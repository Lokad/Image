    [Fact]
    public void OriginalDomainVectorsKeepEveryCoefficientAcrossFactorization()
    {
        // Frozen from the independently expressed matrix on the original
        // domain: constants, impulses, paired boundaries and seeded blocks.
        var input = new short[16]; var output = new short[16]; var encoded = new byte[32];
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256); var vectors = 0;
        void Append()
        {
            Vp8ForwardTransform.Dct(input, output);
            for (var p = 0; p < 16; p++) BinaryPrimitives.WriteInt16LittleEndian(encoded.AsSpan(p * 2), output[p]);
            hash.AppendData(encoded); vectors++;
        }
        for (var value = -255; value <= 255; value++) { Array.Fill(input, (short)value); Append(); }
        for (var position = 0; position < 16; position++)
        for (var value = -255; value <= 255; value++) { Array.Clear(input); input[position] = (short)value; Append(); }
        for (var a = -255; a <= 255; a++)
        for (var b = -255; b <= 255; b++)
        {
            for (var y = 0; y < 4; y++)
            for (var x = 0; x < 4; x++) input[y * 4 + x] = (short)(((x + y) % 4) switch { 0 => a, 1 => b, 2 => -b, _ => -a });
            Append();
        }
        uint state = 0x9e3779b9;
        for (var sample = 0; sample < 32768; sample++)
        {
            for (var p = 0; p < 16; p++)
            { state ^= state << 13; state ^= state >> 17; state ^= state << 5; input[p] = (short)((int)(state % 511) - 255); }
            Append();
        }
        Assert.Equal(302576, vectors);
        Assert.Equal("5deb2b31f8819446c66c9b49009369a3c1eb1d6b944f3579465b2081dbf68d35", Convert.ToHexStringLower(hash.GetHashAndReset()));
    }

